#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Stop reason of the failed trials behind the not-approved repoDB pairs, and a
pair-level stop class, from the 'DetailedStatus' field of repoDB v2.

Design
------
- 'DetailedStatus' of repoDB v2 (conf.REPODB_FILE) is the ClinicalTrials.gov
  "Why Study Stopped" text of each failed (Terminated / Withdrawn / Suspended)
  record. Each distinct text is assigned one stop reason by
  WHY_STOPPED_FILE (columns why_stopped, stop_reason, note), a curated
  table kept in this slug's output folder (one LLM-assisted pass, cross-checked against keyword rules,
  disagreements resolved by hand). Texts are compared after collapsing
  whitespace. Stop reasons: efficacy, safety, efficacy_and_safety,
  interim_unspecified, recruitment, business_funding, regulatory_admin,
  covid, other_evidence, unclear; records without text are 'missing';
  texts not in the table are 'not_curated'.
- Trial level: one row per (pair, NCT) of the not-approved and conflict pairs
  of repodb_signature_lincs_pairs.tsv (output of 04_), with status, phase,
  why_stopped and stop reason.
- Pair level, for every pair of the 04_ table:
  pair_stop_class = the first of efficacy_and_safety, efficacy, safety,
  interim_unspecified found among the pair's trials, else 'non_clinical' if
  at least one trial has a non-clinical reason (recruitment,
  business_funding, regulatory_admin, covid, other_evidence), else 'unknown'
  (only unclear / missing / not_curated); empty for approved pairs.
  clinical_stop_enrolled = the same search restricted to Terminated and
  Suspended trials (Withdrawn trials never enrolled a participant).
  all_withdrawn = every failed trial of the pair is Withdrawn.

Inputs (paths from conf.py)
---------------------------
- conf.REPODB_FILE.
- OOUT_DIR/validations/drug_disease_pairs_validation/repodb_why_stopped_classification.tsv
  (curated by hand; not regenerated by any script).
- OOUT_DIR/validations/drug_disease_pairs_validation/repodb_signature_lincs_pairs.tsv (from 04_).

Outputs (OOUT_DIR/validations/drug_disease_pairs_validation/)
------------------------------------------------------------
- repodb_stop_reason_by_trial.tsv
- repodb_signature_lincs_pairs_stop_reason.tsv : the 04_ table + n_failed_trials,
  trial_stop_reasons, pair_stop_class, clinical_stop_enrolled, all_withdrawn.
- repodb_stop_reason_summary_ge<x>Psamples.tsv : not-approved pairs per
  pair_stop_class and per clinical_stop_enrolled, at >= PSAMPLES (10) Psamples,
  and their distinct trials per stop reason.

Usage
-----
    PYTHONPATH=. python validations/drug_disease_pairs_validation/06_repodb_stop_reason.py   (from src/)
"""

import sys
from pathlib import Path

import pandas as pd

SRC_DIR = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(SRC_DIR))

from conf import REPODB_FILE, OOUT_DIR

SLUG = "drug_disease_pairs_validation"
OUT_DIR = OOUT_DIR / "validations" / SLUG
WHY_STOPPED_FILE = OUT_DIR / "repodb_why_stopped_classification.tsv"
PSAMPLES = 10
CLINICAL = ['efficacy_and_safety', 'efficacy', 'safety', 'interim_unspecified']
NON_CLINICAL = {'recruitment', 'business_funding', 'regulatory_admin', 'covid', 'other_evidence'}


def norm(s):
    return s.str.replace(r'\s+', ' ', regex=True).str.strip()


def pair_class(reasons):
    for c in CLINICAL:
        if c in reasons:
            return c
    return 'non_clinical' if NON_CLINICAL & set(reasons) else 'unknown'


if __name__ == '__main__':
    repo = pd.read_csv(REPODB_FILE)
    failed = repo[repo['status'] != 'Approved'].copy()
    failed['why_stopped'] = norm(failed['DetailedStatus'].astype('string'))
    dec = pd.read_csv(WHY_STOPPED_FILE, sep='\t')
    dec['why_stopped'] = norm(dec['why_stopped'].astype('string'))
    assert not dec['why_stopped'].duplicated().any(), 'duplicated texts in the decision table'
    reason = dict(zip(dec['why_stopped'], dec['stop_reason']))
    failed['stop_reason'] = [('missing' if pd.isna(t) or t == '' else reason.get(t, 'not_curated'))
                             for t in failed['why_stopped']]
    trial_info = (failed.drop_duplicates('NCT')
                  .set_index('NCT')[['status', 'phase', 'why_stopped', 'stop_reason']])

    pairs = pd.read_csv(OUT_DIR / 'repodb_signature_lincs_pairs.tsv', sep='\t')
    rows, per_pair = [], []
    for i, r in pairs.iterrows():
        ncts = [] if pd.isna(r['failed_trials']) else str(r['failed_trials']).split('|')
        info = trial_info.reindex(ncts)
        for nct, t in info.iterrows():
            rows.append({'drugbank_id': r['drugbank_id'], 'drug_name': r['drug_name'], 'ind_id': r['ind_id'],
                         'ind_name': r['ind_name'], 'label': r['label'], 'NCT': nct, **t.to_dict()})
        if r['label'] == 'approved' or not ncts:
            per_pair.append({'n_failed_trials': len(ncts), 'trial_stop_reasons': '', 'pair_stop_class': '',
                             'clinical_stop_enrolled': '', 'all_withdrawn': ''})
            continue
        reasons = info['stop_reason'].fillna('not_curated').tolist()
        enrolled = info.loc[info['status'].isin(['Terminated', 'Suspended']), 'stop_reason'].fillna('not_curated').tolist()
        per_pair.append({'n_failed_trials': len(ncts), 'trial_stop_reasons': '|'.join(reasons),
                         'pair_stop_class': pair_class(reasons),
                         'clinical_stop_enrolled': pair_class(enrolled) if enrolled else 'none_enrolled',
                         'all_withdrawn': bool((info['status'] == 'Withdrawn').all())})
    out = pd.concat([pairs, pd.DataFrame(per_pair, index=pairs.index)], axis=1)
    by_trial = pd.DataFrame(rows)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    by_trial.to_csv(OUT_DIR / 'repodb_stop_reason_by_trial.tsv', sep='\t', index=False)
    out.to_csv(OUT_DIR / 'repodb_signature_lincs_pairs_stop_reason.tsv', sep='\t', index=False)

    na = out[(out['label'] == 'not_approved') & (out['max_psamples'] >= PSAMPLES)]
    summary = pd.concat([
        na['pair_stop_class'].value_counts().rename_axis('class').reset_index(name='n_pairs').assign(view='pair_stop_class'),
        na['clinical_stop_enrolled'].value_counts().rename_axis('class').reset_index(name='n_pairs').assign(view='clinical_stop_enrolled'),
        pd.DataFrame([{'view': 'all_withdrawn', 'class': 'True', 'n_pairs': int((na['all_withdrawn'] == True).sum())}]),
        by_trial.merge(na[['drugbank_id', 'ind_id']], on=['drugbank_id', 'ind_id'])
          .drop_duplicates('NCT')['stop_reason'].value_counts()
          .rename_axis('class').reset_index(name='n_pairs').assign(view='trials_stop_reason (n trials)'),
    ])[['view', 'class', 'n_pairs']]
    summary.to_csv(OUT_DIR / f'repodb_stop_reason_summary_ge{PSAMPLES}Psamples.tsv', sep='\t', index=False)
    print(f'not-approved pairs at >= {PSAMPLES} Psamples: {len(na)}')
    print(summary.to_string(index=False))
